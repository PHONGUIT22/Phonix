"""Pytest session configuration and safety isolation.

Strictly protects the user machine from test mutations:
- Captures snapshots of real ~/.gemini mtimes before any test runs.
- Autouse fixture isolates Path.home, HOME, USERPROFILE, APPDATA, LOCALAPPDATA to a pytest tmp_path.
- Session finish verifies real ~/.gemini remains 100% untouched.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Generator
import pytest

# Capture the real home and snapshot real ~/.gemini before any patching
_REAL_HOME = Path.home()
_REAL_GEMINI = _REAL_HOME / ".gemini"


def _is_agent_runtime_file(p: Path) -> bool:
    # Exclude internal agent harness log/db/transcript files generated by the active test runner session
    name = p.name.lower()
    parts = set(p.parts)
    if any(k in parts for k in ("brain", "conversations", ".system_generated", "antigravity", "antigravity-cli", "bin")):
        return True
    if name in ("cli.log", "agentapi.bat", "agyhub_summaries_proto.pb", "jetbox_summaries_proto.pb"):
        return True
    if name.endswith((".log", ".db-wal", ".db-shm", ".jsonl", ".db", ".bat")):
        return True
    return False


def _snapshot_gemini_mtimes(gemini_dir: Path) -> dict[str, float]:
    mtimes: dict[str, float] = {}
    if not gemini_dir.is_dir():
        return mtimes
    for p in gemini_dir.rglob("*"):
        if p.is_file() and not _is_agent_runtime_file(p):
            try:
                mtimes[str(p)] = p.stat().st_mtime
            except Exception:
                pass
    return mtimes


_INITIAL_GEMINI_MTIMES = _snapshot_gemini_mtimes(_REAL_GEMINI)


def get_real_gemini_violations() -> list[str]:
    """Returns any discrepancies between current ~/.gemini mtimes and initial snapshot."""
    current_mtimes = _snapshot_gemini_mtimes(_REAL_GEMINI)
    violations: list[str] = []

    for path_str, init_mtime in _INITIAL_GEMINI_MTIMES.items():
        if path_str not in current_mtimes:
            violations.append(f"Deleted file in real ~/.gemini: {path_str}")
        elif current_mtimes[path_str] != init_mtime:
            violations.append(
                f"Modified file in real ~/.gemini: {path_str} (mtime {init_mtime} -> {current_mtimes[path_str]})"
            )

    for path_str in current_mtimes:
        if path_str not in _INITIAL_GEMINI_MTIMES:
            violations.append(f"New file created in real ~/.gemini: {path_str}")

    return violations


@pytest.fixture(autouse=True)
def isolate_user_machine_environment(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Generator[Path, None, None]:
    """Points Path.home, HOME, USERPROFILE, APPDATA, LOCALAPPDATA at isolated temp directories."""
    fake_home = tmp_path / "fake_user_home"
    fake_home.mkdir(parents=True, exist_ok=True)
    fake_appdata = fake_home / "AppData" / "Roaming"
    fake_appdata.mkdir(parents=True, exist_ok=True)
    fake_localappdata = fake_home / "AppData" / "Local"
    fake_localappdata.mkdir(parents=True, exist_ok=True)

    monkeypatch.setenv("HOME", str(fake_home))
    monkeypatch.setenv("USERPROFILE", str(fake_home))
    monkeypatch.setenv("APPDATA", str(fake_appdata))
    monkeypatch.setenv("LOCALAPPDATA", str(fake_localappdata))

    # Monkeypatch Path.home()
    monkeypatch.setattr(Path, "home", classmethod(lambda cls: fake_home))

    yield fake_home


def pytest_sessionfinish(session: Any, exitstatus: int) -> None:
    """Verifies that the real ~/.gemini directory was completely untouched throughout the pytest session."""
    violations = get_real_gemini_violations()
    if violations:
        pytest.fail(f"Safety violation: real ~/.gemini directory was modified during tests: {violations}")
